<?php

class PreviewAction extends CAction{
    /**
     * Контроллер, обрабатывающий события вызванные ajax-запросами
     **/
    public function run(){   
		//если запрос асинхронный, то нам нужно отдать только данные
		if(Yii::app()->request->isAjaxRequest){	
            
            // Проверяем существует ли файл на сервере
            // Проверяем размер файла, если он меньше или равен размеру превьюшек - ничего не делаем.
            // Создаем превью в соответствии с параметрами переданными в запросе. Если параметры не были переданы, то делаем превью по дефолтным параметрам
            
               
			Yii::app()->end();
		}else{
			//если запрос не асинхронный, редиректим в корень модуля
			$this->controller->redirect('/backend/filemanager');
		}
    }
    
	public function filters(){
		return array(
			'ajaxOnly + index',
		);
	}
}